const dicts: Record<Language, Record<TKey, string>> = { es, en };
let current: Language = "es";

// El store llama a esta función cuando cambia el idioma.
export function setCurrentLanguage(language: Language) {
  current = language;
}

export function translate(language: Language, key: TKey, vars?: Record<string, string | number>): string {
  let text = dicts[language][key] ?? es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

// Para usar fuera de componentes (store, utilidades): toma el idioma activo.
export function tr(key: TKey, vars?: Record<string, string | number>): string {
  return translate(current, key, vars);
}

// Traduce un mensaje que viene del servidor o de la validación con Zod.
export function translateServerMessage(message: string): string {
  return current === "en" ? serverEn[message] ?? message : message;
}

// Nombre de una competencia del contenido (por ejemplo "Gramática").
export function competencyName(name: string): string {
  const key = `comp.${name}` as TKey;
  return key in es ? tr(key) : name;
}

// Locale para fechas y horas.
export function dateLocale(): string {
  return current === "en" ? "en-US" : "es-CL";
}
